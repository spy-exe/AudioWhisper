import { act, fireEvent, render, screen, waitFor } from "@testing-library/react";
import { afterEach, expect, it, vi } from "vitest";
import { api } from "@/lib/api";
import type { MediaFile, TranscriptSegment } from "@/lib/types";
import { TranscriptEditor } from "@/components/editor/TranscriptEditor";
vi.mock("@/components/editor/Waveform", () => ({ Waveform: () => null }));
vi.mock("@/components/editor/MediaPlayer", () => ({ MediaPlayer: () => null }));
vi.mock("@/components/workspace/AIWorkspace", () => ({ AIWorkspace: () => null }));
vi.mock("@/components/workspace/OrganizationPanel", () => ({ OrganizationPanel: () => null }));
vi.mock("@/components/hub/NotebookView", () => ({ MeetingNotebook: () => null }));
afterEach(() => vi.restoreAllMocks());
it("serializes autosaves so an older request cannot overwrite a newer edit", async () => {
  HTMLElement.prototype.scrollIntoView = vi.fn();
  const segment = { id: "s1", job_id: "j1", segment_index: 0, start: 0, end: 1, text: "Original", confidence: null, words: null, edited: false, updated_at: "2026-10-19T12:00:00Z" } as TranscriptSegment;
  vi.spyOn(api, "getSegments").mockResolvedValue([segment]);
  vi.spyOn(api, "organization").mockResolvedValue({ title: "", folder: "", project: "", tags: [], speakers: {}, diarization_status: "idle", diarization_error: null });
  let resolveFirst!: (value: TranscriptSegment) => void;
  const first = new Promise<TranscriptSegment>((resolve) => { resolveFirst = resolve; });
  const update = vi.spyOn(api, "updateSegment").mockReturnValueOnce(first).mockResolvedValue(segment);
  render(<TranscriptEditor jobId="j1" media={{ id: "m1", original_name: "test.wav", media_type: "audio" } as MediaFile} />);
  const input = await screen.findByRole("textbox", { name: /^Texto em/ });
  fireEvent.change(input, { target: { value: "Primeira edição" } });
  fireEvent.keyDown(window, { key: "s", ctrlKey: true });
  await waitFor(() => expect(update).toHaveBeenCalledTimes(1));
  fireEvent.change(input, { target: { value: "Edição mais recente" } });
  fireEvent.keyDown(window, { key: "s", ctrlKey: true });
  expect(update).toHaveBeenCalledTimes(1);
  await act(async () => resolveFirst(segment));
  await waitFor(() => expect(update).toHaveBeenCalledTimes(2));
  expect(update.mock.calls[1]?.[2]).toBe("Edição mais recente");
});
